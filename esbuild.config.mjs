import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

// D-03: Guard plugin — rejects import of node:fs/electron at bundle time.
// Obsidian provides these at runtime; bundling them would either fail or ship
// host APIs into the DOM-like plugin sandbox.
const guardPlugin = {
	name: 'guard-no-node-builtins',
	setup(build) {
		const forbidden = ['node:fs', 'fs', 'node:electron', 'electron'];
		build.onResolve({ filter: /.*/ }, (args) => {
			if (forbidden.includes(args.path)) {
				return {
					errors: [{
						text: `D-03: forbidden import of '${args.path}' — must be external (provided by Obsidian/runtime)`,
						location: { file: args.importer, namespace: args.namespace, line: 0 },
					}],
					external: false,
				};
			}
		});
	},
};

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	plugins: [guardPlugin],
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	minify: prod,
	mainFields: ['module', 'main'],
	conditions: ['import', 'node'],
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
